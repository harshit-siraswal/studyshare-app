List<String> getSubjectsForClass(String? classLabel) {
  if (classLabel == null || classLabel.isEmpty) return [];
  return _subjectsByClass[classLabel] ?? [];
}

String getClassNumberForBackend(String? classLabel) {
  if (classLabel == null || classLabel.isEmpty) return '';
  if (classLabel.startsWith('Class 9')) return '9';
  if (classLabel.startsWith('Class 10')) return '10';
  if (classLabel.startsWith('Class 11')) return '11';
  if (classLabel.startsWith('Class 12')) return '12';
  return classLabel;
}

bool isSchoolId(String id) {
  return id.trim().toLowerCase() == kSchoolId;
}

bool isSchoolDomain(String domain) {
  return domain.trim().toLowerCase() == kSchoolDomain;
}

bool isSchoolCollege(String? id, String? domain, String? name) {
  if (id != null && isSchoolId(id)) return true;
  if (domain != null && isSchoolDomain(domain)) return true;
  if (name != null && name.toLowerCase().contains('kendriya vidyalaya')) return true;
  return false;
}

